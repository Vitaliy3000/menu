export interface Level {
  label: string;
  value: number;
}

/** Ненулевые уровни по убыванию; при равенстве — в порядке записи. */
export function ranked<K extends string>(levels: Partial<Record<K, number>>, labels: Record<K, string>): Level[] {
  return (Object.entries(levels) as [K, number][])
    .filter(([, value]) => value > 0)
    .sort(([, a], [, b]) => b - a)
    .map(([key, value]) => ({ label: labels[key], value }));
}
